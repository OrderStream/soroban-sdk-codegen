use crate::spec::{ContractFunction, ContractSpec, ContractType, SpecType};

pub struct TypeScriptGenerator;

impl TypeScriptGenerator {
    pub fn generate(spec: &ContractSpec) -> String {
        let mut out = String::new();

        out.push_str("/**\n");
        out.push_str(&format!(" * Type-Safe Stellar Soroban Client SDK for {}\n", spec.contract_name));
        out.push_str(" * Automatically generated by @OrderStream/soroban-sdk-codegen\n");
        out.push_str(" */\n\n");

        out.push_str("export interface RpcClientOptions {\n");
        out.push_str("  rpcUrl: string;\n");
        out.push_str("  networkPassphrase?: string;\n");
        out.push_str("  contractId: string;\n");
        out.push_str("}\n\n");

        // Types & Structs
        for ty in &spec.types {
            match ty {
                ContractType::Struct { name, doc, fields } => {
                    if let Some(d) = doc {
                        out.push_str(&format!("/** {} */\n", d));
                    }
                    out.push_str(&format!("export interface {} {{\n", name));
                    for f in fields {
                        let ts_type = Self::map_type(&f.field_type);
                        out.push_str(&format!("  {}: {};\n", f.name, ts_type));
                    }
                    out.push_str("}\n\n");
                }
                ContractType::Enum { name, doc, variants } => {
                    if let Some(d) = doc {
                        out.push_str(&format!("/** {} */\n", d));
                    }
                    out.push_str(&format!("export enum {} {{\n", name));
                    for v in variants {
                        out.push_str(&format!("  {} = {},\n", v.name, v.value));
                    }
                    out.push_str("}\n\n");
                }
            }
        }

        // Client Class
        let safe_class_name = spec.contract_name.replace('-', "_").replace(' ', "_");
        out.push_str(&format!("export class {}Client {{\n", safe_class_name));
        out.push_str("  public readonly contractId: string;\n");
        out.push_str("  public readonly rpcUrl: string;\n");
        out.push_str("  public readonly networkPassphrase: string;\n\n");

        out.push_str("  constructor(options: RpcClientOptions) {\n");
        out.push_str("    this.contractId = options.contractId;\n");
        out.push_str("    this.rpcUrl = options.rpcUrl;\n");
        out.push_str("    this.networkPassphrase = options.networkPassphrase || 'Test SDF Future Network ; October 2022';\n");
        out.push_str("  }\n\n");

        for func in &spec.functions {
            out.push_str(&Self::generate_function_method(func));
        }

        out.push_str("}\n");
        out
    }

    fn generate_function_method(func: &ContractFunction) -> String {
        let mut method = String::new();
        if let Some(d) = &func.doc {
            method.push_str(&format!("  /**\n   * {}\n   */\n", d));
        }

        let mut args_sig = Vec::new();
        let mut arg_names = Vec::new();
        for arg in &func.inputs {
            let ts_t = Self::map_type(&arg.arg_type);
            args_sig.push(format!("{}: {}", arg.name, ts_t));
            arg_names.push(arg.name.clone());
        }

        let return_type = Self::map_type(&func.output);
        let ret_promise = if return_type == "void" {
            "Promise<void>".to_string()
        } else {
            format!("Promise<{}>", return_type)
        };

        method.push_str(&format!(
            "  async {}({}): {} {{\n",
            func.name,
            args_sig.join(", "),
            ret_promise
        ));

        method.push_str(&format!(
            "    const method = '{}';\n",
            func.name
        ));
        method.push_str(&format!(
            "    const args = [{}];\n",
            arg_names.join(", ")
        ));
        method.push_str("    // Simulated call via Soroban RPC client\n");
        method.push_str("    console.log(`[SDK] Invoking ${method} on contract ${this.contractId}`, args);\n");
        if return_type == "void" {
            method.push_str("    return;\n");
        } else {
            method.push_str(&format!("    return null as unknown as {};\n", return_type));
        }
        method.push_str("  }\n\n");

        method
    }

    fn map_type(spec_type: &SpecType) -> String {
        match spec_type {
            SpecType::Bool => "boolean".into(),
            SpecType::U32 | SpecType::I32 => "number".into(),
            SpecType::U64 | SpecType::I64 | SpecType::U128 | SpecType::I128 => "bigint".into(),
            SpecType::String | SpecType::Symbol | SpecType::Address => "string".into(),
            SpecType::Bytes => "Uint8Array".into(),
            SpecType::Vec(inner) => format!("Array<{}>", Self::map_type(inner)),
            SpecType::Map(k, v) => format!("Record<{}, {}>", Self::map_type(k), Self::map_type(v)),
            SpecType::Custom(name) => name.clone(),
            SpecType::Void => "void".into(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::spec::{ContractFunction, FunctionArg, StructField};

    #[test]
    fn test_ts_codegen() {
        let mut spec = ContractSpec::new("LiquidityPool");
        spec.types.push(ContractType::Struct {
            name: "ReserveConfig".into(),
            doc: Some("Reserve configuration parameters".into()),
            fields: vec![
                StructField {
                    name: "asset_a".into(),
                    field_type: SpecType::Address,
                    doc: None,
                },
                StructField {
                    name: "balance_a".into(),
                    field_type: SpecType::I128,
                    doc: None,
                },
            ],
        });

        spec.functions.push(ContractFunction {
            name: "swap".into(),
            doc: Some("Executes an automated market maker swap".into()),
            inputs: vec![
                FunctionArg {
                    name: "user".into(),
                    arg_type: SpecType::Address,
                    doc: None,
                },
                FunctionArg {
                    name: "amount_in".into(),
                    arg_type: SpecType::I128,
                    doc: None,
                },
            ],
            output: SpecType::I128,
        });

        let ts_code = TypeScriptGenerator::generate(&spec);
        assert!(ts_code.contains("export class LiquidityPoolClient"));
        assert!(ts_code.contains("export interface ReserveConfig"));
        assert!(ts_code.contains("balance_a: bigint;"));
        assert!(ts_code.contains("async swap(user: string, amount_in: bigint): Promise<bigint>"));
    }
}
