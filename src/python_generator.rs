use crate::spec::{ContractFunction, ContractSpec, ContractType, SpecType};

pub struct PythonGenerator;

impl PythonGenerator {
    pub fn generate(spec: &ContractSpec) -> String {
        let mut out = String::new();

        out.push_str("\"\"\"\n");
        out.push_str(&format!("Type-Safe Stellar Soroban Client SDK for {}\n", spec.contract_name));
        out.push_str("Automatically generated by @OrderStream/soroban-sdk-codegen\n");
        out.push_str("\"\"\"\n\n");

        out.push_str("from __future__ import annotations\n");
        out.push_str("from dataclasses import dataclass\n");
        out.push_str("from enum import IntEnum\n");
        out.push_str("from typing import Any, Dict, List, Optional, Union\n\n\n");

        // Types & Structs
        for ty in &spec.types {
            match ty {
                ContractType::Struct { name, doc, fields } => {
                    out.push_str("@dataclass\n");
                    out.push_str(&format!("class {}:\n", name));
                    if let Some(d) = doc {
                        out.push_str(&format!("    \"\"\"{}\"\"\"\n", d));
                    }
                    if fields.is_empty() {
                        out.push_str("    pass\n\n");
                    } else {
                        for f in fields {
                            let py_t = Self::map_type(&f.field_type);
                            let safe_name = Self::sanitize_name(&f.name);
                            out.push_str(&format!("    {}: {}\n", safe_name, py_t));
                        }
                        out.push_str("\n");
                    }
                }
                ContractType::Enum { name, doc, variants } => {
                    out.push_str(&format!("class {}(IntEnum):\n", name));
                    if let Some(d) = doc {
                        out.push_str(&format!("    \"\"\"{}\"\"\"\n", d));
                    }
                    if variants.is_empty() {
                        out.push_str("    pass\n\n");
                    } else {
                        for v in variants {
                            out.push_str(&format!("    {} = {}\n", v.name, v.value));
                        }
                        out.push_str("\n");
                    }
                }
            }
        }

        let safe_class_name = Self::sanitize_identifier(&spec.contract_name);
        // Client Class
        out.push_str(&format!("class {}Client:\n", safe_class_name));
        out.push_str(&format!("    \"\"\"Client wrapper for Stellar Soroban contract `{}`.\"\"\"\n\n", spec.contract_name));
        out.push_str("    def __init__(\n");
        out.push_str("        self,\n");
        out.push_str("        contract_id: str,\n");
        out.push_str("        rpc_url: str = \"https://soroban-testnet.stellar.org\",\n");
        out.push_str("        network_passphrase: str = \"Test SDF Future Network ; October 2022\",\n");
        out.push_str("    ):\n");
        out.push_str("        self.contract_id = contract_id\n");
        out.push_str("        self.rpc_url = rpc_url\n");
        out.push_str("        self.network_passphrase = network_passphrase\n\n");

        for func in &spec.functions {
            out.push_str(&Self::generate_function_method(func));
        }

        out
    }

    fn sanitize_identifier(name: &str) -> String {
        name.replace('-', "_").replace(' ', "_")
    }

    fn sanitize_name(name: &str) -> String {
        match name {
            "from" | "import" | "def" | "class" | "global" | "nonlocal" | "lambda" | "yield"
            | "return" | "pass" | "in" | "is" | "as" | "except" | "finally" | "raise"
            | "try" | "with" | "while" | "for" | "if" | "elif" | "else" | "async" | "await"
            | "assert" | "break" | "continue" | "del" | "type" | "id" => format!("{}_", name),
            _ => name.to_string(),
        }
    }

    fn generate_function_method(func: &ContractFunction) -> String {
        let mut method = String::new();

        let mut args_sig = vec!["self".to_string()];
        let mut arg_dict_entries = Vec::new();
        for arg in &func.inputs {
            let py_t = Self::map_type(&arg.arg_type);
            let safe_name = Self::sanitize_name(&arg.name);
            args_sig.push(format!("{}: {}", safe_name, py_t));
            arg_dict_entries.push(format!("'{}': {}", arg.name, safe_name));
        }

        let return_type = Self::map_type(&func.output);
        let safe_func_name = Self::sanitize_name(&func.name);

        method.push_str(&format!(
            "    def {}({}) -> {}:\n",
            safe_func_name,
            args_sig.join(", "),
            return_type
        ));

        if let Some(d) = &func.doc {
            method.push_str(&format!("        \"\"\"{}\"\"\"\n", d));
        }

        method.push_str(&format!(
            "        payload = {{{}}}\n",
            arg_dict_entries.join(", ")
        ));
        method.push_str(&format!(
            "        # Simulation and RPC dispatch to contract `{}`\n",
            func.name
        ));
        method.push_str(&format!(
            "        print(f\"[SDK-Python] Invoking {{self.contract_id}}::{func_name}\", payload)\n",
            func_name = func.name
        ));

        if return_type == "None" {
            method.push_str("        return None\n\n");
        } else {
            method.push_str(&format!("        return None  # type: ignore\n\n"));
        }

        method
    }

    fn map_type(spec_type: &SpecType) -> String {
        match spec_type {
            SpecType::Bool => "bool".into(),
            SpecType::U32 | SpecType::I32 | SpecType::U64 | SpecType::I64 | SpecType::U128 | SpecType::I128 => "int".into(),
            SpecType::String | SpecType::Symbol | SpecType::Address => "str".into(),
            SpecType::Bytes => "bytes".into(),
            SpecType::Vec(inner) => format!("List[{}]", Self::map_type(inner)),
            SpecType::Map(k, v) => format!("Dict[{}, {}]", Self::map_type(k), Self::map_type(v)),
            SpecType::Custom(name) => name.clone(),
            SpecType::Void => "None".into(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::spec::{ContractFunction, FunctionArg, StructField};

    #[test]
    fn test_python_codegen() {
        let mut spec = ContractSpec::new("LiquidityPool");
        spec.types.push(ContractType::Struct {
            name: "PoolStats".into(),
            doc: Some("Pool metrics".into()),
            fields: vec![
                StructField {
                    name: "tvl".into(),
                    field_type: SpecType::I128,
                    doc: None,
                },
                StructField {
                    name: "fee_bps".into(),
                    field_type: SpecType::U32,
                    doc: None,
                },
            ],
        });

        spec.functions.push(ContractFunction {
            name: "deposit".into(),
            doc: Some("Deposits liquidity into the pool".into()),
            inputs: vec![
                FunctionArg {
                    name: "user".into(),
                    arg_type: SpecType::Address,
                    doc: None,
                },
                FunctionArg {
                    name: "amount".into(),
                    arg_type: SpecType::I128,
                    doc: None,
                },
            ],
            output: SpecType::Void,
        });

        let py_code = PythonGenerator::generate(&spec);
        assert!(py_code.contains("class LiquidityPoolClient:"));
        assert!(py_code.contains("class PoolStats:"));
        assert!(py_code.contains("tvl: int"));
        assert!(py_code.contains("def deposit(self, user: str, amount: int) -> None:"));
    }

    #[test]
    fn test_python_reserved_keyword_sanitization() {
        let mut spec = ContractSpec::new("vault-contract");
        spec.functions.push(ContractFunction {
            name: "import".into(),
            doc: None,
            inputs: vec![
                FunctionArg {
                    name: "from".into(),
                    arg_type: SpecType::Address,
                    doc: None,
                },
            ],
            output: SpecType::Void,
        });

        let py_code = PythonGenerator::generate(&spec);
        assert!(py_code.contains("class vault_contractClient:"));
        assert!(py_code.contains("def import_(self, from_: str) -> None:"));
    }
}
